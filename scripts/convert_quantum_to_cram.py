def clean_math(text: str) -> str:
    # Remove escaping in math: \$ -> $
    # Be careful not to replace \\$ with $ incorrectly
    # Simple replace: \$ -> $
    text = text.replace(r"\$", "$")
    # Clean up double escaped dollars
    return text


def clean_forbidden(text: str) -> str:
    text = text.replace("[推测]", "").replace("[待确认]", "")
    text = text.replace("得分盘", "核心分值").replace("冲刺盘", "提分模块")
    return text


def transform_chapter(idx: int, path: Path) -> str:
    content = path.read_text(encoding="utf-8")
    content = clean_math(content)
    content = clean_forbidden(content)

    # Split frontmatter
    fm_match = re.match(r"^(---\s*\n.*?\n---\s*\n*)", content, flags=re.DOTALL)
    if fm_match:
        fm = fm_match.group(1)
        body = content[fm_match.end():]
    else:
        fm = ""
        body = content

    # Replace ## 本章路线 with ## 考情速览
    radar = EXAM_RADARS.get(idx, "")
    radar_block = f"## 考情速览\n{radar}\n"
    body = re.sub(
        r"(?m)^##\s+本章路线\s*\n.*?(?=\n##\s+(?:题型|考点))",
        lambda _: radar_block,
        body,
        flags=re.DOTALL,
    )

    # In each 题型:
    # 1. Replace ### 先知道什么 with ### 核心考点与速记口诀
    # And inject mnemonics
    types = list(re.finditer(r"(?m)^##\s+((?:题型|考点)(?:[一二三四五六七八九十]+|\d+)\s*[：:].+)$", body))
    end_match = re.search(r"(?m)^##\s+(?:课时过关练习|章末过关|课时练习)\s*$", body)
    end_pos = end_match.start() if end_match else len(body)

    # We can process section by section
    new_parts = []
    last_pos = 0

    for t_idx, m in enumerate(types):
        t_start = m.start()
        t_end = types[t_idx + 1].start() if t_idx + 1 < len(types) else end_pos
        new_parts.append(body[last_pos:t_start])
        block = body[t_start:t_end]

        type_num = t_idx + 1
        mnemonic = MNEMONICS.get(idx, {}).get(type_num, "")

        # Replace ### 先知道什么 with ### 核心考点与速记口诀
        # Also ensure mnemonic is present
        if "### 核心考点与速记口诀" in block:
            pass
        elif "### 先知道什么" in block:
            mnemonic_text = f"\n- **速记口诀**：{mnemonic}\n" if mnemonic else ""
            repl_target = f"### 核心考点与速记口诀\n{mnemonic_text}"
            block = re.sub(
                r"###\s+先知道什么\s*\n",
                lambda _, rt=repl_target: rt,
                block,
                count=1,
            )
        elif "### 核心考点" in block:
            mnemonic_text = f"\n- **速记口诀**：{mnemonic}\n" if mnemonic else ""
            repl_target = f"### 核心考点与速记口诀\n{mnemonic_text}"
            block = re.sub(
                r"###\s+核心考点\s*\n",
                lambda _, rt=repl_target: rt,
                block,
                count=1,
            )

        # Replace ### 从题归纳 or ### 易错与技巧 or ### 解题技巧 with ### 避坑提醒
        block = re.sub(r"###\s+(?:从题归纳|易错与技巧|解题技巧)\s*\n", "### 避坑提醒\n", block)

        new_parts.append(block)
        last_pos = t_end

    # Handle end section: replace ## 章末过关 with ## 课时过关练习
    end_block = body[last_pos:]
    end_block = re.sub(r"##\s+(?:章末过关|课时练习)\s*", "## 课时过关练习\n", end_block)

    # In end section, ensure it has #### 解答 instead of ### 关键步骤与解答
    end_block = re.sub(r"###\s+关键步骤与解答\s*", "#### 解答\n", end_block)

    new_parts.append(end_block)
    full_body = "".join(new_parts)

    # Clean double blank lines or artifacts
    full_body = re.sub(r"\n{3,}", "\n\n", full_body)

    final_content = (fm + full_body).strip() + "\n"
    return final_content


def main():
    chapters_dir = Path("output/量子力学/md/chapters")
    for p in sorted(chapters_dir.glob("*.md")):
        m = re.match(r"^0*(\d+)", p.stem)
        if not m:
            continue
        idx = int(m.group(1))
        converted = transform_chapter(idx, p)
        p.write_text(converted, encoding="utf-8")
        print(f"Chapter {idx} converted.")
        # Validate
        body_only = re.sub(r"^\s*---\s*\n.*?\n---\s*\n*", "", converted, flags=re.DOTALL)
        validate_chapter_markdown(body_only, idx)
        print(f"Chapter {idx} validated successfully!")

if __name__ == "__main__":
    main()
